// One-off offline conversion of the CC0 Innerscene gearbox STEP into a compact,
// quantized TypeScript module (positions int16, exact B-rep normals int8,
// indices uint16) so the showcase assembly loads synchronously with the app.
//
// Source  : https://www.innerscene.com/tools/library/3d-parts/three-planet-4-1-gearbox-open-assembly-2dfb48c4
// License : CC0 1.0 (public domain dedication), downloaded 2026-10-21
// Input   : artifacts/asset-eval/planetary-open.step (unmodified)
// Output  : src/showcase/gearboxData.ts
//
// Run: node scripts/build-showcase.cjs
const occt = require('occt-import-js');
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '../artifacts/asset-eval/planetary-open.step');
const out = path.join(__dirname, '../src/showcase/gearboxData.ts');
const POS_SCALE = 60 / 32767; // +/-60 mm range, ~0.002 mm resolution

occt().then(o => {
  const r = o.ReadStepFile(new Uint8Array(fs.readFileSync(src)), {
    linearUnit: 'millimeter', linearDeflectionType: 'bounding_box_ratio',
    linearDeflection: 0.0005, angularDeflection: 0.18,
  });
  if (!r.success) throw new Error('tessellation failed');
  const meshes = [];
  const chunks = [];
  let offset = 0;
  const push = buf => { const start = offset; chunks.push(buf); offset += buf.length; while (offset % 4) { chunks.push(Buffer.alloc(1)); offset++; } return start; };
  for (const m of r.meshes) {
    const p = m.attributes.position.array, n = m.attributes.normal.array, idx = m.index.array;
    const vc = p.length / 3;
    if (vc > 65535) throw new Error('mesh too large for uint16 indices');
    const qp = new Int16Array(p.length), qn = new Int8Array(n.length);
    for (let i = 0; i < p.length; i++) qp[i] = Math.round(p[i] / POS_SCALE);
    for (let i = 0; i < n.length; i++) qn[i] = Math.round(Math.max(-1, Math.min(1, n[i])) * 127);
    const qi = Uint16Array.from(idx);
    meshes.push({
      name: m.name,
      vertices: vc,
      triangles: idx.length / 3,
      position: push(Buffer.from(qp.buffer)),
      normal: push(Buffer.from(qn.buffer)),
      index: push(Buffer.from(qi.buffer)),
    });
  }
  const b64 = Buffer.concat(chunks).toString('base64');
  fs.writeFileSync(out, `// GENERATED by scripts/build-showcase.cjs. Do not edit by hand.
// Innerscene "Three-planet 4:1 gearbox open assembly", CC0 1.0 public domain.
// https://www.innerscene.com/tools/library/3d-parts/three-planet-4-1-gearbox-open-assembly-2dfb48c4
// STEP frame: millimetres, Z up. Tessellated by occt-import-js 0.0.23 with exact B-rep normals.
export const GEARBOX_POSITION_SCALE = ${POS_SCALE};
export const GEARBOX_MESHES = ${JSON.stringify(meshes)} as const;
export const GEARBOX_DATA = '${b64}';
`);
  console.log(meshes.map(m => `${m.name} ${m.triangles}`).join('\n'));
  console.log('bytes', offset, 'base64', b64.length);

  // Probes used when authoring the added parts: off-axis hole centres on case/ring.
  for (const m of r.meshes) {
    if (!/ring|Lower/.test(m.name)) continue;
    const p = m.attributes.position.array;
    const pts = [];
    for (let k = 0; k < p.length; k += 3) { const rr = Math.hypot(p[k], p[k + 1]); if (rr > 49.6 && rr < 53.8) pts.push([p[k], p[k + 1], p[k + 2]]); }
    const clusters = [];
    for (const q of pts) { const c = clusters.find(c => Math.hypot(c.x - q[0], c.y - q[1]) < 3); if (c) { c.pts.push(q); } else clusters.push({ x: q[0], y: q[1], pts: [q] }); }
    for (const c of clusters) { const cx = c.pts.reduce((s, q) => s + q[0], 0) / c.pts.length, cy = c.pts.reduce((s, q) => s + q[1], 0) / c.pts.length; c.cx = cx; c.cy = cy; c.r = Math.max(...c.pts.map(q => Math.hypot(q[0] - cx, q[1] - cy))); }
    console.log(m.name, clusters.filter(c => c.pts.length > 8).map(c => `(${c.cx.toFixed(2)},${c.cy.toFixed(2)}) r=${c.r.toFixed(2)} R=${Math.hypot(c.cx, c.cy).toFixed(2)} n=${c.pts.length}`).join('  '));
  }
});
